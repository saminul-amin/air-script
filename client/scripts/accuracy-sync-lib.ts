/** Shared by scripts/sync-accuracy.ts (writes) and tests/accuracySync.test.ts (checks). */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DOCS = path.resolve(HERE, "../../docs");
export const OUT = path.resolve(HERE, "../src/data/accuracy.generated.ts");
export const ASSETS = path.resolve(HERE, "../src/assets");

interface Report {
  dataset: string;
  samples: number;
  evaluated_on: string;
  reference: string;
  models: Record<string, { samples: number; top1: number; top3: number; most_confused: { true: string; predicted: string; count: number; share_of_true_class: number }[]; per_class: Record<string, { accuracy: number | null }> }>;
}

export interface AccuracySummary {
  dataset: string;
  samples: number;
  evaluatedOn: string;
  models: { name: string; top1: number; top3: number }[];
  mostConfused: { from: string; to: string; share: number }[];
  weakest: { label: string; accuracy: number }[];
}

function summarise(report: Report): AccuracySummary {
  const ref = report.models[report.reference];
  const weakest = Object.entries(ref.per_class)
    .filter(([, v]) => v.accuracy !== null)
    .map(([label, v]) => ({ label, accuracy: v.accuracy as number }))
    .sort((a, b) => a.accuracy - b.accuracy)
    .slice(0, 5);
  return {
    dataset: report.dataset,
    samples: report.samples,
    evaluatedOn: report.evaluated_on,
    models: Object.entries(report.models).map(([name, m]) => ({ name: name.replace(/\s*\(.*\)$/, ""), top1: m.top1, top3: m.top3 })),
    mostConfused: ref.most_confused.slice(0, 8).map((c) => ({ from: c.true, to: c.predicted, share: c.share_of_true_class })),
    weakest,
  };
}

export function render(): { source: string; images: Record<string, Buffer> } {
  const read = (name: string): Report | null => {
    const file = path.join(DOCS, name);
    return fs.existsSync(file) ? (JSON.parse(fs.readFileSync(file, "utf-8")) as Report) : null;
  };
  const emnist = read("accuracy-emnist.json");
  const bengali = read("accuracy-bengali.json");
  const real = read("accuracy-real-strokes.json");
  if (!emnist || !bengali) throw new Error("docs/accuracy-emnist.json and docs/accuracy-bengali.json are required");

  const data = {
    english: summarise(emnist),
    bengali: summarise(bengali),
    realStrokes: real ? summarise(real) : null,
  };
  const source =
    "// GENERATED by scripts/sync-accuracy.ts from docs/accuracy-*.json. Do not edit.\n" +
    "// Re-run `npm run sync:accuracy` after evaluate.py / evaluate_bn.py / evaluate:real-strokes.\n" +
    'import type { AccuracySummary } from "../../scripts/accuracy-sync-lib";\n\n' +
    "export const ACCURACY: { english: AccuracySummary; bengali: AccuracySummary; realStrokes: AccuracySummary | null } = " +
    JSON.stringify(data, null, 2) +
    ";\n";

  const images: Record<string, Buffer> = {};
  for (const name of ["confusion-matrix-emnist.png", "confusion-matrix-bengali.png"]) {
    const file = path.join(DOCS, name);
    if (fs.existsSync(file)) images[name] = fs.readFileSync(file);
  }
  return { source, images };
}

export function isStale(): string[] {
  const { source, images } = render();
  const stale: string[] = [];
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, "utf-8") !== source) stale.push(path.relative(process.cwd(), OUT));
  for (const [name, bytes] of Object.entries(images)) {
    const target = path.join(ASSETS, name);
    if (!fs.existsSync(target) || !fs.readFileSync(target).equals(bytes)) stale.push(path.relative(process.cwd(), target));
  }
  return stale;
}

